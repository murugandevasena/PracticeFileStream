package PraticeProblems;

import java.util.LinkedHashMap;

public class FindFrequencyOfEachWord {
    static void main() {
        String g="இனியும் தாமதிக்காமல், கள்ளக்குறிச்சி தவெக சட்டமன்ற உறுப்பினரைக் கைது செய்து விசாரிக்க வேண்டும்” என்று திமுக தலைவர் ஸ்டாலின் வலியுறுத்தியுள்ளார்.\n" +
                "\n" +
                "இது தொடர்பாக அவர் தனது எக்ஸ் பதிவில் கூறியிருப்பதாவது: “ஆளுங்கட்சியைச் சேர்ந்த எம்எல்ஏ-வின் ஒழுங்கீனமான செயல் குறித்து மாவட்ட ஆட்சியர் முறையாகப் புகார் அளித்திருக்கும் செய்தி 'தி இந்து' நாளேட்டில் இன்று வெளியாகியிருக்கிறது.\n" +
                "\n" +
                "இத்தகைய ஒரு சம்பவம் நடைபெற்றதாக பல வாரங்களுக்கு முன்பு செய்திகள் வெளிவரத் தொடங்கியபோதே, முதலமைச்சரும் தலைமைச் செயலாளரும் மாவட்ட ஆட்சியரை அழைத்துப் பேசி இருக்க வேண்டும். அவருக்கு உறுதுணையாக அரசு இருக்கும் என்ற நம்பிக்கையை அளித்திருக்க வேண்டும்";

        LinkedHashMap<String, Integer> lhm= new LinkedHashMap<>();
        for(String s1:g.split(" ")){
            if(lhm.containsKey(s1)){
                lhm.put(s1,lhm.get(s1));
            } else {
                lhm.put(s1,1);
            }
        }
        System.out.println("Repeated strings: "+lhm);
    }
}
